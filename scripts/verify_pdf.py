#!/usr/bin/env python3
"""Verify the built report PDF: page count, repaired sentences, upright units.

Run with the project venv's python (pymupdf lives there, not in the
execute_code sandbox):
    python
        scripts/verify_pdf.py
"""
import os
import re
import sys
import unicodedata

import fitz

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PDF = os.path.join(ROOT, "report", "main.pdf")
OUT = os.path.join(ROOT, "notes", "_final_pdf_text.txt")

# The 8 sentences that the stray-'$' repair must have restored to prose.
# Each is given in the whitespace-normalised form the PDF extractor yields.
PROBES = [
    ("ex1 c_inlet 600 um", "The view is zoomed to the first 600 µm of the channel, "
                           "and the colour bar runs from 0 to 1 mol/m3."),
    ("ex1 c_inlet 1 mol/m3", "1 mol/m3. Generated by"),
    # the caption was rewritten in 2026-10-24: the plot is a plan view, so the
    # field is uniform across the WIDTH and the Poiseuille profile is across
    # the depth, which this view does not show.  The probe only has to find
    # the sentence as upright prose.
    ("ex1 u_inlet m/s", "m/s that the flow rate demands. The field is uniform "
                        "across the width of the channel in this plan view"),
    ("ex2 60x60", "of the 60 × 60 mm footprint is only reached by diffusion, "
                   "which is slow."),
    ("ex2 t = 2195", "at t = 2195 s, and never reaches 0.9"),
    ("ex4 0.3 um", "mesh sixfold moves the final height by 0.3 µm, so the graded "
                   "mesh is converged for this question."),
    ("ex4 28.5 / 3.5 um", "comes to rest at 28.5 µm, within 3.5 µm of the "
                          "analytical equilibrium."),
    ("ex4 4 mm channel", "given 4 mm instead of 1 mm of channel, the same particle"),
    ("ex1 comparison table", "0.94730 0.95213 0.94853"),
    ("ex4 variant table", "73 195 17.0 39.79"),
    ("ex4 mesh elements", "73 195 mesh elements, 91 particles released"),
]

# numbers that must be present somewhere in the report
NUMBERS = ["0.94730", "0.95213", "0.94853", "0.50009", "0.49992",
           "73 195", "438 933", "314 455", "9696", "0.003284"]


def norm(s):
    """Fold ligatures and dashes so that a probe written in plain ASCII
    matches the PDF's typeset output.

    NFKC normalisation is the right tool: the PDF uses the typographic
    ligature codepoints (U+FB00 "ff", U+FB01 "fi", U+FB02 "fl", ...) and
    the multiplication sign U+00D7, none of which appear in a probe
    written as plain text.  NFKC decomposes all of them to their ASCII
    equivalents in one step -- hand-listing the ligature codepoints
    misses some (U+FB00 was missed the first time).
    """
    s = unicodedata.normalize("NFKC", s)
    s = s.replace("\u2013", "-").replace("\u2014", "--")
    s = s.replace("\u00d7", "x")          # multiplication sign -> 'x'
    return re.sub(r"\s+", " ", s).strip()


def main():
    doc = fitz.open(PDF)
    pages = [p.get_text() for p in doc]
    txt = "\n".join(pages)
    flat = norm(txt)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(txt)

    print("PDF      : %s" % PDF)
    print("size     : %.2f MiB" % (os.path.getsize(PDF) / 1048576))
    print("pages    : %d" % doc.page_count)
    print("chars    : %d" % len(txt))

    print("\n--- repaired sentences must appear as PROSE ---")
    bad = 0
    for label, probe in PROBES:
        hit = norm(probe) in flat
        if not hit:
            bad += 1
        print("   %-22s %s" % (label, "OK" if hit else "*** NOT FOUND ***"))
        if not hit:
            key = norm(probe)[:38]
            i = flat.find(key)
            if i >= 0:
                print("        actual: %r" % flat[i:i + 130])

    print("\n--- key numbers present in the rendered report ---")
    for n in NUMBERS:
        ok = norm(n) in flat
        if not ok:
            bad += 1
        print("   %-12s %s" % (n, "OK" if ok else "*** MISSING ***"))

    print("\n--- unit glyphs (upright \\mathrm must render as plain text) ---")
    for u in ["µm", "mol/m3", "mm", "m/s", "Pa"]:
        print("   %-8s %d" % (u, len(re.findall(re.escape(u), txt))))

    # every page must carry text
    blank = [i + 1 for i, t in enumerate(pages) if len(t.strip()) < 40]
    print("\nblank/near-blank pages: %s" % (blank or "none"))
    if blank:
        bad += len(blank)

    print("\nRESULT: %s" % ("ALL CHECKS PASSED" if bad == 0 else "%d PROBLEM(S)" % bad))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
